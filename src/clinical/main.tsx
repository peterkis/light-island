import {StrictMode,lazy,Suspense} from 'react';
import {createRoot} from 'react-dom/client';
import './tokens.css';
import './clinical.css';
import './uiux.css';
const SourcePage=lazy(()=>import('./SourcePage'));
const ClinicalApp=lazy(()=>import('./ClinicalApp'));
const query=new URLSearchParams(location.search),ticket=query.get('source');
document.documentElement.classList.toggle('clinical-native',query.get('view')==='island'&&!ticket);
createRoot(document.getElementById('root')!).render(<StrictMode><Suspense fallback={<div className="cs-loading">正在打开只读工作空间…</div>}>{ticket?<SourcePage ticket={ticket}/>:<ClinicalApp/>}</Suspense></StrictMode>);
